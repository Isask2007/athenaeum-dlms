export const resources = raw.map((item, index) => {
  const title = item.title;
  const abstract = item.abstract;
  const description = item.description;
  const coverSlug = title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  const fileUrl = item.file ? `/digital/${item.file}.pdf` : '';
  return {
    ...item,
    subtitle: item.subtitle || '',
    isbn: item.isbn || '',
    issn: item.issn || '',
    total_copies: item.format === 'physical' ? item.copies : 1,
    available_copies: item.format === 'physical' ? item.copies : 1,
    file_url: fileUrl,
    file_type: fileUrl ? 'pdf' : item.format === 'physical' ? '' : 'text',
    license_info: item.license || '',
    page_count: item.pages || 0,
    pages_json: item.format === 'physical' ? [] : pagesFor(title, abstract, description),
    cover_url: `/covers/${coverSlug}.svg`,
    tags: item.tags,
    views: 40 + ((index * 37) % 380),
    borrows: 3 + ((index * 11) % 60),
    description,
    abstract,
  };
});

